// Bundles the example docs MDX pages into a TypeScript module, because the
// Worker build cannot import .mdx files as text.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const directory = fileURLToPath(
  new URL("../src/services/example-docs/", import.meta.url),
);

export async function renderExampleDocsModule() {
  const names = (await readdir(`${directory}pages`))
    .filter((name) => name.endsWith(".mdx"))
    .sort();
  const entries = await Promise.all(
    names.map(async (name) => {
      const content = await readFile(`${directory}pages/${name}`, "utf8");
      return `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`;
    }),
  );
  return [
    "// Generated by scripts/generate-example-docs.mjs. Do not edit.",
    "// Edit the files in ./pages, then run `pnpm --filter @doxahq/api generate:example-docs`.",
    "export const EXAMPLE_DOCS_PAGE_SOURCES: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(
    `${directory}pages.generated.ts`,
    await renderExampleDocsModule(),
  );
}
