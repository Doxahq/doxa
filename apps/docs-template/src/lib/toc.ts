import {
  activeTocIndex,
  tocScrollTargets,
  tocTriggers,
  type TocScrollMetrics,
} from "@doxahq/docs-prose";

/**
 * The reading line sits at the headings' `scroll-margin-top`: the height of
 * the sticky navbar and section tabs, plus a gap. A browser jump to `#id`
 * puts a heading at the same place. This value is used when a heading has no
 * scroll margin: the navbar (h-16) plus 16px.
 */
const FALLBACK_READING_OFFSET = 80;

export const APP_SCROLL_CONTAINER_ID = "app-scroll-container";

export interface ScrollRootMetrics {
  scrollTop: number;
  viewportHeight: number;
  scrollHeight: number;
  rootTop: number;
}

/** Strip the leading `#` from a TOC href to get the element ID. */
export function hrefToId(href: string): string {
  return href.startsWith("#") ? href.slice(1) : href;
}

export function getAppScrollContainer(): HTMLElement | null {
  return document.getElementById(APP_SCROLL_CONTAINER_ID);
}

function isWindowScrollRoot(
  scrollRoot: HTMLElement | Window
): scrollRoot is Window {
  return typeof Window !== "undefined" && scrollRoot instanceof Window;
}

export function getScrollRootMetrics(
  scrollRoot: HTMLElement | Window
): ScrollRootMetrics {
  if (isWindowScrollRoot(scrollRoot)) {
    return {
      scrollTop: window.scrollY,
      viewportHeight: window.innerHeight,
      scrollHeight: document.documentElement.scrollHeight,
      rootTop: 0,
    };
  }

  return {
    scrollTop: scrollRoot.scrollTop,
    viewportHeight: scrollRoot.clientHeight,
    scrollHeight: scrollRoot.scrollHeight,
    rootTop: scrollRoot.getBoundingClientRect().top,
  };
}

/**
 * Resolve TOC ids to actual DOM heading elements.
 * Falls back to querying `<article>` headings directly when the
 * computed slugs don't match the IDs generated by rehype-slug.
 */
export function findHeadingElements(tocIds: string[]): HTMLElement[] {
  const byId = tocIds
    .map((id) => document.getElementById(id))
    .filter(Boolean) as HTMLElement[];

  if (byId.length > 0) return byId;

  const article = document.querySelector("article");
  if (!article) return [];
  return Array.from(
    article.querySelectorAll<HTMLElement>("h2[id], h3[id], h4[id]")
  );
}

function readingOffset(heading: HTMLElement): number {
  const margin = Number.parseFloat(getComputedStyle(heading).scrollMarginTop);
  return margin > 0 ? margin : FALLBACK_READING_OFFSET;
}

/** Each heading's top in the scroll content. */
function headingTops(
  headings: HTMLElement[],
  metrics: ScrollRootMetrics
): number[] {
  return headings.map(
    (heading) =>
      heading.getBoundingClientRect().top - metrics.rootTop + metrics.scrollTop
  );
}

function tocMetrics(
  headings: HTMLElement[],
  metrics: ScrollRootMetrics
): TocScrollMetrics {
  return {
    maxScroll: metrics.scrollHeight - metrics.viewportHeight,
    viewportHeight: metrics.viewportHeight,
    readingOffset: headings[0] ? readingOffset(headings[0]) : 0,
  };
}

/**
 * The ID of the current heading. Short sections at the end of the page become
 * current before the bottom (see `tocTriggers`).
 */
export function findActiveHeadingId(
  headings: HTMLElement[],
  metrics: ScrollRootMetrics
): string {
  const triggers = tocTriggers(
    headingTops(headings, metrics),
    tocMetrics(headings, metrics)
  );
  return headings[activeTocIndex(triggers, metrics.scrollTop)]?.id ?? "";
}

/**
 * Scrolls `target` as near the reading line as the page allows, with `target`
 * still the current heading when the scroll stops. An element that is not one
 * of `headings` scrolls into view.
 */
export function scrollToHeading(
  scrollRoot: HTMLElement | Window,
  headings: HTMLElement[],
  target: HTMLElement,
  behavior: ScrollBehavior
): void {
  const index = headings.indexOf(target);
  if (index === -1) {
    target.scrollIntoView({ behavior });
    return;
  }
  const metrics = getScrollRootMetrics(scrollRoot);
  const targets = tocScrollTargets(
    headingTops(headings, metrics),
    tocMetrics(headings, metrics)
  );
  scrollRoot.scrollTo({ top: targets[index], behavior });
}
