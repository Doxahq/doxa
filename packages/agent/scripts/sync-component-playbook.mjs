// Copies apps/docs-template/agent/component-playbook.md into the agent bundle.
// The hosted writer runs from the built package, where the template file does
// not exist. tests/component-playbook.test.ts fails when the copy is stale.
//
// Usage: node scripts/sync-component-playbook.mjs

import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../../../apps/docs-template/agent/component-playbook.md", import.meta.url);
const target = new URL("../src/doxa-agent/prompts/component-playbook.generated.ts", import.meta.url);

export function renderPlaybookModule(markdown) {
  const literal = markdown
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
  return [
    "// Generated by scripts/sync-component-playbook.mjs from",
    "// apps/docs-template/agent/component-playbook.md. Do not edit by hand.",
    "",
    "/** The MDX component reference appended to every writer system prompt. */",
    `export const COMPONENT_PLAYBOOK = \`${literal}\`;`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const markdown = await readFile(source, "utf8");
  await writeFile(target, renderPlaybookModule(markdown));
  console.log(`Wrote ${target.pathname}`);
}
