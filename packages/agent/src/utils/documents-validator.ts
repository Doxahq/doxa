/**
 * Documents.ts Validator
 * Validates the generated documents.ts navigation config to ensure
 * it follows the correct flat structure with headings, items, and spacers.
 *
 * Expected format:
 *   { heading: "Section Name" }
 *   { title: "Page Title", href: "/path" }
 *   { spacer: true }
 */

export interface DocumentsValidationError {
  line: number;
  message: string;
  severity: "error" | "warning";
}

export interface DocumentsValidationResult {
  valid: boolean;
  errors: DocumentsValidationError[];
}

/**
 * Parsed representation of a single entry in the Documents array
 */
type ParsedEntry =
  | { type: "heading"; value: string }
  | { type: "item"; title: string; href: string }
  | { type: "spacer" };

/**
 * Validate the generated documents.ts content string.
 * Checks structural rules:
 * 1. Must start with the correct import
 * 2. Must have the auto-generated comment
 * 3. Must export `Documents` as `Paths[]`
 * 4. Array entries must be heading, item (title+href), or spacer
 * 5. Headings must be followed by at least one item
 * 6. Spacers must only appear between sections (not first, not last, not consecutive)
 * 7. No duplicate hrefs
 * 8. All hrefs must start with "/"
 * 9. Last entry must not be a spacer
 */
export function validateDocumentsConfig(content: string): DocumentsValidationResult {
  const errors: DocumentsValidationError[] = [];
  const lines = content.split("\n");

  // Rule 1: Must start with import
  if (!content.includes('import { Paths } from "@/src/lib/pageroutes"')) {
    errors.push({
      line: 1,
      message: 'Missing required import: import { Paths } from "@/src/lib/pageroutes"',
      severity: "error",
    });
  }

  // Rule 2: Must have auto-generated comment
  if (!content.includes("Auto-generated by docs-generator")) {
    errors.push({
      line: 2,
      message: "Missing auto-generated comment header",
      severity: "warning",
    });
  }

  // Rule 3: Must export Documents as Paths[]
  if (!content.includes("export const Documents: Paths[] =")) {
    errors.push({
      line: 1,
      message: "Missing export: export const Documents: Paths[]",
      severity: "error",
    });
  }

  // Parse entries from the array
  const entries = parseDocumentEntries(content);

  if (entries.length === 0) {
    errors.push({
      line: 1,
      message: "Documents array is empty - no navigation entries found",
      severity: "error",
    });
    return { valid: false, errors };
  }

  // Rule 4: First entry must be a heading
  if (entries[0].type !== "heading") {
    errors.push({
      line: 1,
      message: `First entry must be a heading, got: ${entries[0].type}`,
      severity: "error",
    });
  }

  // Rule 9: Last entry must not be a spacer
  if (entries[entries.length - 1].type === "spacer") {
    errors.push({
      line: entries.length,
      message: "Last entry must not be a spacer",
      severity: "error",
    });
  }

  const seenHrefs = new Set<string>();
  let lastType: string | null = null;
  let itemCountAfterHeading = 0;

  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i];
    const lineNum = i + 1;

    if (entry.type === "heading") {
      // Rule 5: Check that previous heading had at least one item
      if (lastType === "heading") {
        errors.push({
          line: lineNum - 1,
          message: "Heading must be followed by at least one item before next heading/spacer",
          severity: "error",
        });
      }
      if (lastType === "spacer" && itemCountAfterHeading === 0 && i > 1) {
        // spacer followed by heading without items in previous section is ok
        // only flag if the heading before the spacer had no items
      }

      // Validate heading value
      if (!entry.value || entry.value.trim() === "") {
        errors.push({
          line: lineNum,
          message: "Heading value must not be empty",
          severity: "error",
        });
      }

      itemCountAfterHeading = 0;
    }

    if (entry.type === "item") {
      itemCountAfterHeading++;

      // Rule 8: href must start with "/"
      if (!entry.href.startsWith("/")) {
        errors.push({
          line: lineNum,
          message: `href must start with "/": got "${entry.href}"`,
          severity: "error",
        });
      }

      // Rule 7: No duplicate hrefs
      if (seenHrefs.has(entry.href)) {
        errors.push({
          line: lineNum,
          message: `Duplicate href found: "${entry.href}"`,
          severity: "error",
        });
      }
      seenHrefs.add(entry.href);

      // Validate title
      if (!entry.title || entry.title.trim() === "") {
        errors.push({
          line: lineNum,
          message: "Item title must not be empty",
          severity: "error",
        });
      }
    }

    if (entry.type === "spacer") {
      // Rule 6: No consecutive spacers
      if (lastType === "spacer") {
        errors.push({
          line: lineNum,
          message: "Consecutive spacers are not allowed",
          severity: "error",
        });
      }

      // Rule 6: Spacer can't be first
      if (i === 0) {
        errors.push({
          line: lineNum,
          message: "First entry must not be a spacer",
          severity: "error",
        });
      }

      // Check that the section before the spacer had items
      if (itemCountAfterHeading === 0 && lastType !== "item") {
        errors.push({
          line: lineNum,
          message: "Spacer found without any items in the preceding section",
          severity: "warning",
        });
      }
    }

    lastType = entry.type;
  }

  // Final check: last heading must have items
  if (lastType === "heading") {
    errors.push({
      line: entries.length,
      message: "Trailing heading with no items",
      severity: "error",
    });
  }

  const hasErrors = errors.some((e) => e.severity === "error");
  return { valid: !hasErrors, errors };
}

/**
 * Parse entry objects from the Documents array in the generated TypeScript string.
 */
function parseDocumentEntries(content: string): ParsedEntry[] {
  const entries: ParsedEntry[] = [];

  // Match the array content between [ and ]
  const arrayMatch = content.match(/Documents:\s*Paths\[\]\s*=\s*\[([\s\S]*)\]/);
  if (!arrayMatch) return entries;

  const arrayContent = arrayMatch[1];

  // Match individual object entries: { ... }
  const entryRegex = /\{([^}]+)\}/g;
  let match: RegExpExecArray | null;

  while ((match = entryRegex.exec(arrayContent)) !== null) {
    const inner = match[1].trim();

    // Check for heading
    const headingMatch = inner.match(/heading:\s*"([^"]*)"/);
    if (headingMatch) {
      entries.push({ type: "heading", value: headingMatch[1] });
      continue;
    }

    // Check for spacer
    if (/spacer:\s*true/.test(inner)) {
      entries.push({ type: "spacer" });
      continue;
    }

    // Check for item (title + href)
    const titleMatch = inner.match(/title:\s*"([^"]*)"/);
    const hrefMatch = inner.match(/href:\s*"([^"]*)"/);
    if (titleMatch && hrefMatch) {
      entries.push({
        type: "item",
        title: titleMatch[1],
        href: hrefMatch[1],
      });
      continue;
    }
  }

  return entries;
}
